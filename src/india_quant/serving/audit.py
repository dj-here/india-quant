@dataclass
class AuditRecord:
    audit_id: str
    timestamp_ist: str
    symbol: str
    model_name: str
    model_version: str
    feature_hash_sha256: str
    prob_win: float
    direction: int
    predicted_high: float
    predicted_low: float
    abstain: bool
    record_signature_sha256: str


class AuditLogger:
    """
    Maintains a cryptographically verifiable audit log of every prediction.
    """

    def __init__(self, log_dir: str = "./data/lake/audit"):
        self.log_dir = Path(log_dir)
        try:
            self.log_dir.mkdir(parents=True, exist_ok=True)
        except OSError:
            self.log_dir = Path("/tmp/india_quant/audit")
            try:
                self.log_dir.mkdir(parents=True, exist_ok=True)
            except OSError:
                pass
        self.log_file = self.log_dir / "prediction_audit_trail.jsonl"

    @staticmethod
    def compute_sha256(data: Any) -> str:
        """Computes SHA-256 hash of a serializable object or string."""
        serialized = json.dumps(data, sort_keys=True, default=str)
        return hashlib.sha256(serialized.encode("utf-8")).hexdigest()

    def log_prediction(
        self,
        symbol: str,
        model_name: str,
        model_version: str,
        features: Dict[str, float],
        prob_win: float,
        direction: int,
        predicted_high: float,
        predicted_low: float,
        abstain: bool,
    ) -> AuditRecord:
        """
        Creates, hashes, and persists an immutable audit record for a single prediction.
        """
        now_ist = datetime.now(tz=IST).isoformat()
        feat_hash = self.compute_sha256(features)

        core_payload = {
            "timestamp_ist": now_ist,
            "symbol": symbol,
            "model_name": model_name,
            "model_version": model_version,
            "feature_hash": feat_hash,
            "prob_win": prob_win,
            "direction": direction,
            "predicted_high": predicted_high,
            "predicted_low": predicted_low,
            "abstain": abstain,
        }
        sig = self.compute_sha256(core_payload)
        audit_id = f"AUD-{sig[:12].upper()}"

        record = AuditRecord(
            audit_id=audit_id,
            timestamp_ist=now_ist,
            symbol=symbol,
            model_name=model_name,
            model_version=model_version,
            feature_hash_sha256=feat_hash,
            prob_win=prob_win,
            direction=direction,
            predicted_high=predicted_high,
            predicted_low=predicted_low,
            abstain=abstain,
            record_signature_sha256=sig,
        )

        # Append to JSONL audit log
        try:
            with open(self.log_file, "a", encoding="utf-8") as f:
                f.write(json.dumps(asdict(record)) + "\n")
        except OSError:
            pass

        return record

    def load_recent_audit_records(self, limit: int = 50) -> List[AuditRecord]:
        """Reads recent audit records from disk."""
        if not self.log_file.exists():
            return []
        records = []
        with open(self.log_file, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    records.append(AuditRecord(**json.loads(line.strip())))
        return records[-limit:]
