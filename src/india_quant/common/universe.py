def get_universe_by_class(asset_class: Optional[AssetClass] = None) -> List[AssetDefinition]:
    """Returns assets filtered by class or all assets if None."""
    if asset_class is None:
        return list(MARKET_UNIVERSE.values())
    return [asset for asset in MARKET_UNIVERSE.values() if asset.asset_class == asset_class]


def get_all_symbols() -> List[str]:
    """Returns list of all registered symbols."""
    return list(MARKET_UNIVERSE.keys())


def get_asset_def(symbol: str) -> Optional[AssetDefinition]:
    """Retrieves definition for a symbol with case-insensitive matching."""
    if symbol in MARKET_UNIVERSE:
        return MARKET_UNIVERSE[symbol]
    upper = symbol.upper().strip()
    for k, v in MARKET_UNIVERSE.items():
        if k.upper() == upper or v.symbol.upper() == upper:
            return v
    return None
